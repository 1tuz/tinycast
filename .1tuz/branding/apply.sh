#!/bin/bash
# Apply the product identity AFTER the upstream patch queue. Safe to rerun.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
base=.1tuz/branding

cp "$base/README.md" README.md
cp "$base/INSTALL.md" INSTALL.md
cp "$base/icon.json" Tinycast/tinycast.icon/icon.json
cp "$base/icon.svg" Tinycast/tinycast.icon/Assets/speechcast.svg
cp "$base/menuicon.json" Tinycast/Assets.xcassets/MenuBarIcon.imageset/Contents.json
cp "$base/menubar.svg" Tinycast/Assets.xcassets/MenuBarIcon.imageset/speechcast.svg
cp "$base/logo.svg" docs/speechcast-logo.svg
cp "$base/distribution.md" docs/speechcast-distribution.md
cp "$base/install.sh" Scripts/install.sh
cp "$base/build-dmg.sh" Scripts/build-dmg.sh
cp "$base/release-notes.sh" Scripts/release-notes.sh
chmod +x Scripts/install.sh Scripts/build-dmg.sh Scripts/release-notes.sh
rm -f Tinycast/tinycast.icon/Assets/voicecast.svg \
    Tinycast/Assets.xcassets/MenuBarIcon.imageset/voicecast.svg \
    docs/voicecast-logo.svg docs/voicecast-distribution.md

python3 - <<'PY'
from pathlib import Path

def change(path, old, new):
    p = Path(path)
    data = p.read_text()
    if new in data:
        return  # Idempotent: the replacement often contains the original anchor.
    if old in data:
        p.write_text(data.replace(old, new))
    else:
        raise SystemExit(f"speechcast branding: missing anchor in {path}: {old!r}")

change("project.yml", "        PRODUCT_BUNDLE_IDENTIFIER: \"$(TINYCAST_BUNDLE_IDENTIFIER)\"",
       "        PRODUCT_NAME: SpeechCast\n        PRODUCT_BUNDLE_IDENTIFIER: \"$(TINYCAST_BUNDLE_IDENTIFIER)\"")
change("project.yml", "          PRODUCT_NAME: Tinycast Dev",
       "          PRODUCT_NAME: SpeechCast Dev")
change("Tinycast/Info.plist", "\t<key>CFBundleName</key>",
       "\t<key>CFBundleDisplayName</key>\n\t<string>SpeechCast</string>\n\t<key>CFBundleName</key>")
change("Tinycast/Info.plist",
       "\t\t\t\t<string>tinycast</string>\n\t\t\t\t<string>com.raycast</string>",
       "\t\t\t\t<string>tinycast</string>\n\t\t\t\t<string>voicecast</string>\n\t\t\t\t<string>com.raycast</string>")
info = Path("Tinycast/Info.plist")
data = info.read_text().replace("Raycast and Tinycast URL Scheme", "Raycast and SpeechCast URL Scheme")
data = data.replace("Tinycast Backup", "SpeechCast Backup").replace("Tinycast uses", "SpeechCast uses")
data = data.replace("Tinycast captures", "SpeechCast captures").replace("Tinycast shows", "SpeechCast shows")
data = data.replace("Tinycast accesses", "SpeechCast accesses").replace("Tinycast lets", "SpeechCast lets")
data = data.replace("<string>Tinycast</string>", "<string>SpeechCast</string>")
info.write_text(data)

change("Tinycast/Platform/AppDisplayName.swift", '?? "Tinycast"', '?? "SpeechCast"')
try:
    change("Tinycast/Features/Updates/Service/UpdateInstaller.swift",
           'Replacing Tinycast…', 'Replacing SpeechCast…')
except SystemExit:
    pass  # Patch 0021 may already carry the VoiceCast spelling; the post-pass renames it.
change("Tinycast/Windows/About/AboutView.swift", 'A tiny, native macOS launcher.',
       'Your native command center for search, voice, and automation.')
change("Tinycast/Windows/About/AboutView.swift",
       '''id: "discord", glyph: .brand("BrandDiscord"), title: "Discord",
            detail: String(localized: "Join the Tinycast community"),
            url: URL(string: "https://discord.gg/v2Eeb4QQy3")!''',
       '''id: "upstream", glyph: .brand("BrandGitHub"), title: "Original Tinycast",
            detail: "github.com/abue-ammar/tinycast",
            url: URL(string: "https://github.com/abue-ammar/tinycast")!''')
change("Tinycast/Windows/About/AboutView.swift",
       '''id: "x", glyph: .brand("BrandX"), title: "X", detail: "@abue_ammar",
            url: URL(string: "https://x.com/abue_ammar")!''',
       '''id: "speech-runtime", glyph: .symbol("waveform"), title: "Speech Runtime",
            detail: "github.com/1tuz/Speech-Runtime",
            url: URL(string: "https://github.com/1tuz/Speech-Runtime")!''')
change("Tinycast/Windows/About/AboutView.swift",
       'id: "email", glyph: .symbol("envelope"), title: String(localized: "Email")',
       'id: "email", glyph: .symbol("envelope"), title: "Upstream contact"')
change("Tinycast/Windows/About/AboutView.swift",
       'detail: "iabueammar@gmail.com"',
       'detail: "Original Tinycast author: iabueammar@gmail.com"')

# Product-name replacements in localized permission strings (NOT file extensions,
# bundle identifiers, backup UTIs, test fixture names or URL-scheme compatibility).
strings = Path("Tinycast/Resources/InfoPlist.xcstrings")
strings.write_text(strings.read_text().replace("Tinycast", "SpeechCast"))

# Development keeps the Tinycast target and scheme for compatibility with upstream.
# The generated Xcode project is regenerated by .1tuz/apply.sh during every sync.
PY

# Idempotent post-pass: the patch queue and upstream syncs can still drop a
# VoiceCast spelling; any that survives becomes SpeechCast, and voicecast-named
# output files are renamed to their speechcast equivalents.
while IFS= read -r -d '' file; do
    if grep -qF 'VoiceCast' "$file"; then
        echo "speechcast branding: converting leftover VoiceCast in $file"
        python3 -c "
import sys
from pathlib import Path
p = Path(sys.argv[1])
p.write_text(p.read_text().replace('VoiceCast', 'SpeechCast'))" "$file"
    fi
done < <(grep -rlZF 'VoiceCast' \
        --include='*.swift' --include='*.md' --include='*.sh' --include='*.yml' \
        --include='*.json' --include='*.plist' --include='*.xcstrings' --include='*.svg' \
        . 2>/dev/null || true)
while IFS= read -r -d '' file; do
    case "$file" in ./.1tuz/patches/*) continue ;; esac
    dir=$(dirname "$file")
    name=$(basename "$file")
    renamed="$dir/${name/voicecast/speechcast}"
    if [ "$renamed" != "$file" ] && [ ! -e "$renamed" ]; then
        echo "speechcast branding: renaming $file -> $renamed"
        mv "$file" "$renamed"
    fi
done < <(find . -path ./.git -prune -o -name '*voicecast*' -print0 2>/dev/null || true)

echo "speechcast: branding overlay applied"

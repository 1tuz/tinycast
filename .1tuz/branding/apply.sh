#!/bin/bash
# Apply the product identity AFTER the upstream patch queue. Safe to rerun.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
base=.1tuz/branding

cp "$base/README.md" README.md
cp "$base/INSTALL.md" INSTALL.md
cp "$base/icon.json" Tinycast/tinycast.icon/icon.json
cp "$base/icon.svg" Tinycast/tinycast.icon/Assets/voicecast.svg
cp "$base/menuicon.json" Tinycast/Assets.xcassets/MenuBarIcon.imageset/Contents.json
cp "$base/menubar.svg" Tinycast/Assets.xcassets/MenuBarIcon.imageset/voicecast.svg
cp "$base/logo.svg" docs/voicecast-logo.svg
cp "$base/distribution.md" docs/voicecast-distribution.md
cp "$base/install.sh" Scripts/install.sh
cp "$base/build-dmg.sh" Scripts/build-dmg.sh
cp "$base/release-notes.sh" Scripts/release-notes.sh
chmod +x Scripts/install.sh Scripts/build-dmg.sh Scripts/release-notes.sh

python3 - <<'PY'
from pathlib import Path

def change(path, old, new):
    p = Path(path)
    data = p.read_text()
    if new in data:
        return  # Idempotent: the replacement often contains the original anchor.
    if old in data:
        p.write_text(data.replace(old, new))
    else:
        raise SystemExit(f"voicecast branding: missing anchor in {path}: {old!r}")

change("project.yml", "        PRODUCT_BUNDLE_IDENTIFIER: \"$(TINYCAST_BUNDLE_IDENTIFIER)\"",
       "        PRODUCT_NAME: VoiceCast\n        PRODUCT_BUNDLE_IDENTIFIER: \"$(TINYCAST_BUNDLE_IDENTIFIER)\"")
change("project.yml", "          PRODUCT_NAME: Tinycast Dev",
       "          PRODUCT_NAME: VoiceCast Dev")
change("Tinycast/Info.plist", "\t<key>CFBundleName</key>",
       "\t<key>CFBundleDisplayName</key>\n\t<string>VoiceCast</string>\n\t<key>CFBundleName</key>")
change("Tinycast/Info.plist",
       "\t\t\t\t<string>tinycast</string>\n\t\t\t\t<string>com.raycast</string>",
       "\t\t\t\t<string>tinycast</string>\n\t\t\t\t<string>voicecast</string>\n\t\t\t\t<string>com.raycast</string>")
info = Path("Tinycast/Info.plist")
data = info.read_text().replace("Raycast and Tinycast URL Scheme", "Raycast and VoiceCast URL Scheme")
data = data.replace("Tinycast Backup", "VoiceCast Backup").replace("Tinycast uses", "VoiceCast uses")
data = data.replace("Tinycast captures", "VoiceCast captures").replace("Tinycast shows", "VoiceCast shows")
data = data.replace("Tinycast accesses", "VoiceCast accesses").replace("Tinycast lets", "VoiceCast lets")
data = data.replace("<string>Tinycast</string>", "<string>VoiceCast</string>")
info.write_text(data)

change("Tinycast/Platform/AppDisplayName.swift", '?? "Tinycast"', '?? "VoiceCast"')
change("Tinycast/Features/Updates/Service/UpdateInstaller.swift", 'Replacing Tinycast…', 'Replacing VoiceCast…')
change("Tinycast/Windows/About/AboutView.swift", 'A tiny, native macOS launcher.',
       'Your native command center for search, voice, and automation.')
change("Tinycast/Windows/About/AboutView.swift",
       '''id: "discord", glyph: .brand("BrandDiscord"), title: "Discord",
            detail: String(localized: "Join the Tinycast community"),
            url: URL(string: "https://discord.gg/v2Eeb4QQy3")!''',
       '''id: "upstream", glyph: .brand("BrandGitHub"), title: "Original Tinycast",
            detail: "github.com/abue-ammar/tinycast",
            url: URL(string: "https://github.com/abue-ammar/tinycast")!''')
change("Tinycast/Windows/About/AboutView.swift",
       '''id: "x", glyph: .brand("BrandX"), title: "X", detail: "@abue_ammar",
            url: URL(string: "https://x.com/abue_ammar")!''',
       '''id: "speech-runtime", glyph: .symbol("waveform"), title: "Speech Runtime",
            detail: "github.com/1tuz/Speech-Runtime",
            url: URL(string: "https://github.com/1tuz/Speech-Runtime")!''')
change("Tinycast/Windows/About/AboutView.swift",
       'id: "email", glyph: .symbol("envelope"), title: String(localized: "Email")',
       'id: "email", glyph: .symbol("envelope"), title: "Upstream contact"')
change("Tinycast/Windows/About/AboutView.swift",
       'detail: "iabueammar@gmail.com"',
       'detail: "Original Tinycast author: iabueammar@gmail.com"')

# Product-name replacements in localized permission strings (NOT file extensions,
# bundle identifiers, backup UTIs, test fixture names or URL-scheme compatibility).
strings = Path("Tinycast/Resources/InfoPlist.xcstrings")
strings.write_text(strings.read_text().replace("Tinycast", "VoiceCast"))

# Development keeps the Tinycast target and scheme for compatibility with upstream.
# The generated Xcode project is regenerated by .1tuz/apply.sh during every sync.
PY

echo "voicecast: branding overlay applied"
